import os
import re
import unicodedata
from typing import Optional, List
try:
    import pymupdf
except ImportError as err:
    raise ImportError(
        "PyMuPDF is required by DndPdfEngine but not installed in this environment. "
        "Please activate the virtual environment ('source .venv/bin/activate') "
        "or install it with 'pip install pymupdf'."
    ) from err
from .glossary import DndGlossary
from .translator import DndTranslator

class DndPdfEngine:
    def __init__(self, glossary: Optional[DndGlossary] = None, translator: Optional[DndTranslator] = None):
        self.glossary = glossary or DndGlossary()
        self.translator = translator or DndTranslator(self.glossary)

    def translate_pdf(self, input_path: str, output_path: str) -> None:
        if not os.path.exists(input_path):
            raise FileNotFoundError(f"File not found: {input_path}")

        print(f"Processing: {input_path} -> {output_path}")
        doc = pymupdf.open(input_path)

        for p_no in range(len(doc)):
            page = doc[p_no]
            self._translate_page(page, p_no + 1)

        os.makedirs(os.path.dirname(os.path.abspath(output_path)), exist_ok=True)
        doc.save(output_path)
        print(f"Successfully saved: {output_path}")

    def _translate_page(self, page: pymupdf.Page, page_num: int) -> None:
        # Step 1: Translate form fields (widgets)
        widget_values = set()
        widget_rects = []
        for w in page.widgets():
            val = str(w.field_value or '').strip()
            if not val:
                continue
            # Store original values for detection
            widget_values.add(val)
            widget_rects.append(w.rect)

            # Skip flags / checkboxes
            if val in ['Yes', 'No', 'Off', 'Ja']:
                continue
            # Skip purely numeric/modifier fields
            if re.match(r'^[+\-]?[0-9]+(\.[0-9]+)?$', val):
                continue

            trans_val = self.translator.translate(val)
            if trans_val != val:
                w.field_value = trans_val
                w.update()

        # Step 2: Collect static text blocks
        replacements = []
        for b in page.get_text('blocks'):
            b_rect = pymupdf.Rect(b[:4])
            txt = unicodedata.normalize('NFKD', b[4]).strip()
            if not txt or len(txt) < 2 or re.match(r'^[+\-]?[0-9]+(\.[0-9]+)?$', txt):
                continue

            # Protect widgets: skip if lines in block match any widget field value
            lines = [l.strip() for l in txt.splitlines() if l.strip()]
            if any(l in widget_values for l in lines):
                continue

            # Protect widgets: skip if significant overlap with non-empty widget rect
            is_w = False
            for wr in widget_rects:
                inter = b_rect & wr
                if not inter.is_empty and (inter.get_area() / b_rect.get_area()) > 0.4:
                    is_w = True
                    break
            if is_w:
                continue

            # Footer credits
            if 'generated by' in txt.lower():
                replacements.append(('footer', b_rect, txt, 'Questa scheda del personaggio è stata generata da Aurora Builder.'))
                continue

            # Check feature pattern: Title. Description
            m = re.match(r'^([A-Z][A-Za-z0-9\s’\',\-–—\(\)/]+?)\.\s+(.*)$', txt, re.DOTALL)
            if m and len(m.group(1)) <= 50 and '\n' not in m.group(1):
                title, desc = m.group(1).strip(), m.group(2).strip()
                trans_title = self.glossary.lookup(title)
                if trans_title != title:
                    trans_desc = self.translator.translate(desc)
                    replacements.append(('feature', b_rect, trans_title, trans_desc))
                    continue

            # Check multiline labels in glossary
            if len(lines) > 1 and all(self.glossary.lookup(l) != l for l in lines):
                trans_txt = '\n'.join(self.glossary.lookup(l) for l in lines)
                replacements.append(('label', b_rect, txt, trans_txt))
                continue

            # Check single label in glossary
            single_trans = self.glossary.lookup(txt)
            if single_trans != txt:
                replacements.append(('label', b_rect, txt, single_trans))
                continue

            # Description block (e.g. background feature text, spell cards, notes)
            if len(txt) > 25:
                trans_desc = self.translator.translate(txt)
                if trans_desc != txt:
                    replacements.append(('desc', b_rect, txt, trans_desc))
                    continue

        # Step 3: Add and apply redactions
        for item in replacements:
            page.add_redact_annot(item[1], fill=(1, 1, 1))

        page.apply_redactions()

        # Step 4: Insert new translated text
        for item in replacements:
            kind, rect = item[0], item[1]
            if kind == 'feature':
                title, desc = item[2], item[3]
                html = f'<div style="font-family: sans-serif; font-size: 7.0pt; line-height: 1.15; color: black;"><b><i>{title}.</i></b> {desc}</div>'
                page.insert_htmlbox(rect, html, scale_low=0)
            elif kind == 'label':
                orig_txt, trans_txt = item[2], item[3]
                align = 'center' if (orig_txt.isupper() or rect.width < 90) else 'left'
                weight = 'bold' if orig_txt.isupper() else 'normal'
                fs = '6.5pt' if rect.height < 10 else ('8.0pt' if rect.height > 15 else '7.0pt')
                html_txt = trans_txt.replace('\n', '<br>')
                html = f'<div style="font-family: sans-serif; font-size: {fs}; text-align: {align}; font-weight: {weight}; line-height: 1.05; color: black;">{html_txt}</div>'
                page.insert_htmlbox(rect, html, scale_low=0)
            elif kind == 'desc':
                trans_desc = item[3]
                html_txt = trans_desc.replace('\n', '<br>')
                html = f'<div style="font-family: sans-serif; font-size: 6.8pt; line-height: 1.15; color: black;">{html_txt}</div>'
                page.insert_htmlbox(rect, html, scale_low=0)
            elif kind == 'footer':
                html = f'<div style="font-family: sans-serif; font-size: 5.5pt; text-align: center; color: #555555;">{item[3]}</div>'
                page.insert_htmlbox(rect, html, scale_low=0)
